// High-resolution 16-bit pixel art sprites & RLE span renderer for Pixel Chemist
// Extracted and quantized directly from the generated pixel-art design sheets.

export interface PixelSpan {
  x: number;
  y: number;
  w: number;
  ch: string;
}

export interface CompiledSprite {
  width: number;
  height: number;
  spans: PixelSpan[];
  defaultPalette: Record<string, string>;
}

export interface LegStrideAnim {
  waistY: number;
  splitX: number;
  swingY: number;
  swingX?: number;
}

export function compileSprite(
  rows: string[],
  defaultPalette: Record<string, string> = {}
): CompiledSprite {
  const height = rows.length;
  const width = rows[0]?.length || 0;
  const spans: PixelSpan[] = [];

  for (let y = 0; y < height; y++) {
    const row = rows[y];
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      if (ch === '.' || ch === ' ') {
        x++;
        continue;
      }
      let w = 1;
      while (x + w < row.length && row[x + w] === ch) {
        w++;
      }
      spans.push({ x, y, w, ch });
      x += w;
    }
  }

  return { width, height, spans, defaultPalette };
}

export function drawCompiledSprite(
  ctx: CanvasRenderingContext2D,
  sprite: CompiledSprite,
  cx: number,
  cy: number,
  ux: number,
  uy: number,
  paletteOverrides: Record<string, string> = {},
  flipX: boolean = false,
  legStride?: LegStrideAnim
): void {
  const halfW = sprite.width / 2;
  const halfH = sprite.height / 2;
  const spans = sprite.spans;
  const defPal = sprite.defaultPalette;

  for (let i = 0; i < spans.length; i++) {
    const s = spans[i];
    const color = paletteOverrides[s.ch] || defPal[s.ch];
    if (!color) continue;
    ctx.fillStyle = color;

    let offX = 0;
    let offY = 0;
    if (legStride && s.y >= legStride.waistY) {
      const isRightLeg = s.x + s.w * 0.5 >= legStride.splitX;
      const sign = isRightLeg ? 1 : -1;
      offY = sign * legStride.swingY;
      if (legStride.swingX) {
        offX = sign * legStride.swingX * (flipX ? -1 : 1);
      }
    }

    const drawX = flipX
      ? cx + (halfW - (s.x + s.w) + offX) * ux
      : cx + (s.x - halfW + offX) * ux;
    const drawY = cy + (s.y - halfH + offY) * uy;
    ctx.fillRect(drawX, drawY, s.w * ux + 0.35, uy + 0.35);
  }
}

