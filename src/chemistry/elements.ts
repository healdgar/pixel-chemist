export type MatterState = 'empty' | 'solid' | 'powder' | 'liquid' | 'gas' | 'energy';

export interface ElementDef {
  id: ElementId;
  symbol: string;
  name: string;
  formula: string;
  category: 'structural' | 'powder' | 'liquid' | 'gas' | 'nuclear' | 'quantum';
  state: MatterState;
  density: number; // kg/m^3 relative scale
  baseColor: [number, number, number];
  colorVariance: number;
  glow?: [number, number, number, number]; // r, g, b, intensity (0..1)
  thermalConductivity: number; // 0..1
  defaultTemp: number; // Celsius
  meltPoint?: number;
  meltInto?: ElementId;
  freezePoint?: number;
  freezeInto?: ElementId;
  boilPoint?: number;
  boilInto?: ElementId;
  flammable?: boolean;
  corrodible?: number; // 0..1 susceptibility to acid
  pressureThresholdGPa?: number; // GPa to fracture or compress
  pressureInto?: ElementId;
  weakDecayInto?: ElementId; // Weak force (W/Z boson) transmutation target
  radioactivity: number; // Sieverts/s
  description: string;
}

